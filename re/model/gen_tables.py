"""Emit src/mods/pitchtools/pitch_tables.h from the fitted model tables + vibrato renders."""
import numpy as np, pickle, os
from load import load
from model import build_tables, MS_PER_TICK

T = build_tables()
S2 = load('set2.csv')
out = []
w = out.append
w('/* Generated by re/model/gen_tables.py from VOCALOID4 renders - do not edit. */')
w('#pragma once')

# transition shapes: group 0 = up (rising, risePort>0), 1 = down-falling, 2 = down-kind but rising (risePort 0)
groups = [('up', True), ('down', False), ('down', True)]
w('#define PT_SHAPE_N 201')
w('static const float kShape[3][4][PT_SHAPE_N] = {')
for kind, rising in groups:
    w(' {')
    for b in (1, 2, 5, 12):
        s = T['shape'][(kind, b, rising)]
        w('  {' + ','.join(f'{x:.4f}f' for x in s) + '},')
    w(' },')
w('};')

# recovery curves: 1 at the dip -> 0, every 5 ms for 1000 ms
w('#define PT_REC_N 201')
def recs(d, lens):
    return [T['rec'][(d, L)][::5][:201] for L in lens]
w('static const float kRecUp[5][PT_REC_N] = {' + ','.join('{' + ','.join(f'{x:.4f}f' for x in r) + '}' for r in recs('up', [0, 25, 50, 75, 100])) + '};')
w('static const float kRecDown[5][PT_REC_N] = {' + ','.join('{' + ','.join(f'{x:.4f}f' for x in r) + '}' for r in recs('down', [0, 25, 50, 75, 100])) + '};')
w('static const float kRecStart[11][PT_REC_N] = {' + ','.join('{' + ','.join(f'{x:.4f}f' for x in r) + '}' for r in recs('start', list(range(0, 101, 10)))) + '};')

# vibrato templates: cents, every 2 ms from vibrato start, 4000 ms; fading types at 3 vibrato lengths
VN = 2000
w(f'#define PT_VIB_N {VN}')
w('#define PT_VIB_STEP_MS 2')
def vib(k):
    c = S2[k]; h = c['h']
    t = (c['t'] - h['partPos'] - h['pos2']) * MS_PER_TICK
    v = c['final'] - c['pit']
    g = np.arange(VN) * 2.0
    return np.interp(g, t, v, right=0), h['dur2'] * MS_PER_TICK
rows = []
lens = []
for typ in range(1, 17):
    for d in range(3):
        s, L = vib(191 + (typ - 1) * 3 + d)
        rows.append(s); lens.append(L)
w('/* [type-1][0..2] = vibrato rendered over notes of kVibLenMs[type-1][i] ms (100% vibrato) */')
w('static const float kVibLenMs[16][3] = {' + ','.join('{' + ','.join(f'{lens[(t*3)+i]:.1f}f' for i in range(3)) + '}' for t in range(16)) + '};')
w('static const short kVib[16][3][PT_VIB_N] = {')
for t in range(16):
    w(' {' + ','.join('{' + ','.join(str(int(round(x * 10))) for x in rows[t * 3 + i]) + '}' for i in range(3)) + '},')
w('};')
w('/* types whose depth fades toward the note end need the length-matched template */')
w('static const unsigned char kVibFades[16] = { 0,0,0,1, 0,0,0,1, 0,0,0,1, 0,0,0,1 };')
open('../../src/mods/pitchtools/pitch_tables.h', 'w').write('\n'.join(out) + '\n')
print('ok', sum(len(x) for x in out) // 1024, 'KB')
